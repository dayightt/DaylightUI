local stub = require("stub")

local function spots()
    local _, ns = stub.Load({ module = true, login = false })
    return ns.Spots
end

local BOX = { w = 100, h = 30, padX = 2, padY = 3, cutL = 0, cutR = 0, topInset = 0, bottomInset = 0 }

local function box(over)
    local b = {}
    for k, v in pairs(BOX) do b[k] = v end
    for k, v in pairs(over or {}) do b[k] = v end
    return b
end

T.test("a spot inside: the row's start pinned to that corner, growing the chosen way", function()
    local S = spots()
    local L = S.Layout("bottomleft", "right", box(), {})
    T.eq(L.point, "BOTTOMLEFT"); T.eq(L.relPoint, "BOTTOMLEFT")
    T.eq(L.x, 2); T.eq(L.y, 3)
    T.eq(L.flowAnchor, "BOTTOMLEFT"); T.eq(L.hDir, "Right"); T.eq(L.vDir, "Up")
    L = S.Layout("topright", "left", box(), {})
    T.eq(L.point, "TOPRIGHT"); T.eq(L.relPoint, "TOPRIGHT")
    T.eq(L.x, -2); T.eq(L.y, -3)
    T.eq(L.flowAnchor, "TOPRIGHT"); T.eq(L.hDir, "Left"); T.eq(L.vDir, "Down")
end)

T.test("grow from the middle pins the row's middle (the game's resize keeps it centered)", function()
    local S = spots()
    local L = S.Layout("top", "center", box(), {})
    T.eq(L.point, "TOP"); T.eq(L.relPoint, "TOP"); T.eq(L.x, 0)
    L = S.Layout("center", "center", box(), {})
    T.eq(L.point, "CENTER"); T.eq(L.relPoint, "CENTER"); T.eq(L.x, 0); T.eq(L.y, 0)
    L = S.Layout("above", "center", box(), {})
    T.eq(L.point, "BOTTOM"); T.eq(L.relPoint, "TOP"); T.eq(L.y, S.GAP)
end)

T.test("outside spots sit off the frame's edge", function()
    local S = spots()
    local L = S.Layout("above", "right", box(), {})
    T.eq(L.point, "BOTTOMLEFT"); T.eq(L.relPoint, "TOPLEFT"); T.eq(L.x, 0); T.eq(L.y, S.GAP); T.eq(L.vDir, "Up")
    L = S.Layout("below", "left", box(), {})
    T.eq(L.point, "TOPRIGHT"); T.eq(L.relPoint, "BOTTOMRIGHT"); T.eq(L.y, -S.GAP); T.eq(L.vDir, "Down")
    L = S.Layout("outleft", "right", box(), { line = 40 })
    T.eq(L.point, "RIGHT"); T.eq(L.relPoint, "LEFT"); T.eq(L.x, -S.GAP); T.eq(L.y, 0); T.eq(L.hDir, "Left")
    T.eq(L.line, 40)
    L = S.Layout("outright", "left", box(), { line = 40 })
    T.eq(L.point, "LEFT"); T.eq(L.relPoint, "RIGHT"); T.eq(L.x, S.GAP); T.eq(L.hDir, "Right")
end)

T.test("outside corners: the piece sits off the frame's corner, growing away from it", function()
    local S = spots()
    local L = S.Layout("outtopleft", "right", box(), {})
    T.eq(L.point, "BOTTOMRIGHT"); T.eq(L.relPoint, "TOPLEFT"); T.eq(L.x, -S.GAP); T.eq(L.y, S.GAP)
    T.eq(L.hDir, "Left"); T.eq(L.vDir, "Up")
    L = S.Layout("outtopright", "left", box(), {})
    T.eq(L.point, "BOTTOMLEFT"); T.eq(L.relPoint, "TOPRIGHT"); T.eq(L.x, S.GAP); T.eq(L.hDir, "Right")
    L = S.Layout("outbottomleft", "right", box({ below = 5 }), {})
    T.eq(L.point, "TOPRIGHT"); T.eq(L.relPoint, "BOTTOMLEFT"); T.eq(L.y, -(S.GAP + 5)); T.eq(L.vDir, "Down")
    L = S.Layout("outbottomright", "right", box(), {})
    T.eq(L.point, "TOPLEFT"); T.eq(L.relPoint, "BOTTOMRIGHT")
    local dots = S.Dots(box())
    T.eq(#dots, 17, "9 on the frame, 8 round it")
    T.eq(S.Nearest(dots, -10, -10), "outtopleft")
    T.eq(S.Nearest(dots, 110, 40), "outbottomright")
    T.eq(S.Nearest(dots, -10, 15), "outleft")
end)

T.test("the angled end is kept clear: spots on that side move in, inside rows get shorter", function()
    local S = spots()
    local L = S.Layout("bottomright", "left", box({ cutR = 9 }), { line = 500 })
    T.eq(L.x, -(2 + 9))
    T.eq(L.line, 100 - 2 * 2 - 9, "capped at the room left of the cut")
    L = S.Layout("topleft", "right", box({ cutL = 7 }), {})
    T.eq(L.x, 2 + 7)
    L = S.Layout("bottomleft", "right", box({ cutR = 9 }), {})
    T.eq(L.x, 2, "the other side keeps its pad")
end)

T.test("the power bar, a corner icon and a name tab push spots clear", function()
    local S = spots()
    T.eq(S.Layout("bottom", "center", box({ bottomInset = 4 }), {}).y, 3 + 4)
    T.eq(S.Layout("top", "center", box({ topInset = 5 }), {}).y, -(3 + 5))
    T.eq(S.Layout("topleft", "right", box({ topReserve = 12 }), {}).line, 100 - 4 - 12)
    T.eq(S.Layout("above", "right", box({ above = 16 }), {}).y, S.GAP + 16)
    T.eq(S.Layout("below", "right", box({ below = 5 }), {}).y, -(S.GAP + 5))
end)

T.test("nudges add on; unknown spots and grows fall back to the middle, growing right", function()
    local S = spots()
    local L = S.Layout("center", "center", box(), { x = 5, y = -4 })
    T.eq(L.x, 5); T.eq(L.y, -4)
    L = S.Layout("nowhere", "sideways", box(), {})
    T.eq(L.relPoint, "CENTER"); T.eq(L.point, "LEFT"); T.eq(L.hDir, "Right")
end)

T.test("every spot has a label and a dot; the nearest dot wins", function()
    local S = spots()
    for _, s in ipairs(S.ORDER) do T.truthy(S.LABELS[s], s) end
    local dots = S.Dots(box({ cutR = 9 }))
    T.eq(#dots, #S.ORDER)
    T.eq(S.Nearest(dots, 1, 1), "topleft")
    T.eq(S.Nearest(dots, 50, 15), "center")
    T.eq(S.Nearest(dots, 50, -20), "above")
    local tr
    for _, d in ipairs(dots) do if d.spot == "topright" then tr = d end end
    T.eq(tr.x, 100 - 2 - 9, "the slanted side's dots sit in from the cut")
end)

T.test("a drop near a dot snaps onto it; anywhere else keeps the offset as a nudge", function()
    local S = spots()
    local dots = S.Dots(box())
    local spot, x, y = S.Drop(dots, 52, 17)
    T.eq(spot, "center"); T.eq(x, 0); T.eq(y, 0)
    spot, x, y = S.Drop(dots, 50 + 20, 15 + 1)
    T.eq(spot, "center"); T.eq(x, 20); T.eq(y, -1, "y up, as SetPoint takes it")
end)

T.test("a corner icon pushes a row in that corner past it, and shortens it", function()
    local S = spots()
    local L = S.Layout("bottomright", "left", box({ corners = { bottomright = 12 } }), {})
    T.eq(L.x, -(2 + 12))
    T.eq(L.line, 100 - 4 - 12)
    L = S.Layout("bottomleft", "right", box({ corners = { bottomright = 12 } }), {})
    T.eq(L.x, 2, "another corner's icon changes nothing")
end)

T.test("a resize is clamped and rounded to the step", function()
    local S = spots()
    T.eq(S.Resize(14, 3.4, 10, 32, 1), 17)
    T.eq(S.Resize(14, -10, 10, 32, 1), 10)
    T.eq(S.Resize(30, 9, 10, 32, 1), 32)
    T.eq(S.Resize(100, 7, 40, 160, 5), 105)
end)

T.test("a portrait ring past the outer end: beside spots clear it, rows over and under start past it", function()
    local S = spots()
    local b = box({ outL = 30, aboveInL = 22, belowInL = 14 })
    local L = S.Layout("outleft", "left", b, {})
    T.eq(L.x, -(S.GAP + 30), "beside the frame, past the ring")
    T.eq(S.Layout("outtopleft", "left", b, {}).x, -(S.GAP + 30))
    T.eq(S.Layout("outright", "right", b, {}).x, S.GAP, "the other side has no ring")
    T.eq(S.Layout("below", "right", b, {}).x, 14, "under the frame, from past the ring")
    T.eq(S.Layout("above", "right", b, {}).x, 22, "over the frame, from past the name tab's start")
    T.eq(S.Layout("below", "left", b, {}).x, 0, "pinned at the other end: nothing in the way")
    T.eq(S.Layout("below", "center", b, {}).x, 0)
    local R = S.Layout("below", "left", box({ belowInR = 9 }), {})
    T.eq(R.x, -9, "a ring on the right end")
    local dots = S.Dots(b)
    for _, d in ipairs(dots) do
        if d.spot == "outleft" then T.eq(d.x, -S.DOT_OUT - 30, "its dot past the ring too") end
    end
end)
