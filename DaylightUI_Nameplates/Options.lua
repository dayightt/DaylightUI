-- The nameplates' options, as data: one tab per page.

local _, ns = ...

local function off(key) return function(get) return get(key) ~= true end end
local function execOff(get) return get("execute") == "off" end
-- Styles with no lit band: just the line, or the spell icon.
local function noBand(get) local s = get("executeStyle"); return s == "line" or s == "icon" end

-- Placement rows for a piece (Plate.PlaceSpots): its spot around or on the health
-- bar, an aura row's grow direction, and nudges. name is the label, k its keys
-- { spot, grow?, x, y }. outside limits it to spots around the bar (aura icons
-- are taller than the bar).
local Spots = DaylightUI.Spots
local OUT_LABELS, OUT_ORDER = {}, {}
for _, s in ipairs(ns.OUTSIDE_SPOTS) do
    OUT_LABELS[s], OUT_ORDER[#OUT_ORDER + 1] = Spots.LABELS[s], s
end
local SPOT_DESC = "Over, under, beside or on the health bar. Pieces sharing a spot line up outward from the bar. In Design mode on the preview, drag it there."
local ROW_DESC = "Over, under or beside the health bar. Rows sharing a spot line up outward from the bar. In Design mode on the preview, drag it there."

local function spotItems(name, k, outside, dis, desc)
    local items = {
        { type = "dropdown", key = k.spot, label = name .. " position", values = outside and OUT_LABELS or Spots.LABELS,
          order = outside and OUT_ORDER or Spots.ORDER, desc = desc or (outside and ROW_DESC or SPOT_DESC), disabled = dis },
    }
    if k.grow then
        items[#items + 1] = { type = "dropdown", key = k.grow, label = name .. " grow direction",
            values = Spots.GROW_LABELS, order = Spots.GROW_ORDER, disabled = dis,
            desc = "Which way the row adds its icons, starting from its position.",
            hidden = function(get) local s = get(k.spot); return s == "outleft" or s == "outright" end }
    end
    items[#items + 1] = { type = "slider", key = k.x, label = name .. " left / right", min = -50, max = 50, step = 1,
        unit = "px", disabled = dis, desc = "Nudges it left or right from its position, in pixels." }
    items[#items + 1] = { type = "slider", key = k.y, label = name .. " up / down", min = -50, max = 50, step = 1,
        unit = "px", disabled = dis, desc = "Nudges it up or down from its position, in pixels." }
    return items
end

-- items, each marked new in version.
local function since(version, items)
    for _, item in ipairs(items) do item.since = version end
    return items
end

-- Threat color rows: one color each, or a color pair (the same pairs as the
-- Gradients page) when Threat color style is Two-color gradient. The friendly
-- name pickers only show with Name color on Custom.
local function notCustomName(get) return get("friendly.nameColor") ~= "custom" end

local function isPair(get) return get("threatFill") == "pair" end
local function notPair(get) return get("threatFill") ~= "pair" end
local function threatPair(pair, label)
    local item = DaylightUI.Gradients.Item(pair, label)
    item.since = "1.5.2"
    item.hidden = notPair
    item.disabled = off("threat")
    return item
end

-- items with more added at the end.
local function with(items, more)
    for _, item in ipairs(more) do items[#items + 1] = item end
    return items
end

